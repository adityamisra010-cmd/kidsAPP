#!/usr/bin/env python3
"""
Translation helper for the app's i18n files (src/i18n/locales/<lang>/<namespace>.json).

  python3 scripts/i18n-tools.py export <lang> [ns ...]   numbered "n|English|current" lines for translators
  python3 scripts/i18n-tools.py apply <lang> <file>      apply "n|translation" lines (from export numbering)
  python3 scripts/i18n-tools.py loaders                  regenerate src/i18n/locales/loaders.ts
  python3 scripts/i18n-tools.py check                    validate every language against English

Keys, {{placeholders}}, **bold** markers and plural suffixes (_one/_other) must stay as in English.
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'i18n', 'locales')
CORE = ['common', 'auth', 'parent', 'errors', 'notifications', 'chips', 'settings']
PH = re.compile(r'\{\{\s*[\w.]+\s*\}\}')


def flat(d, prefix=''):
    out = {}
    for k, v in d.items():
        if k == '_review':
            continue
        key = f'{prefix}{k}'
        if isinstance(v, dict):
            out.update(flat(v, key + '.'))
        else:
            out[key] = str(v)
    return out


def unflat(pairs):
    root = {}
    for key, val in pairs.items():
        node = root
        parts = key.split('.')
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = val
    return root


def load(lang, ns):
    p = os.path.join(ROOT, lang, f'{ns}.json')
    return json.load(open(p, encoding='utf8')) if os.path.exists(p) else {}


def namespaces():
    return sorted(f[:-5] for f in os.listdir(os.path.join(ROOT, 'en')) if f.endswith('.json'))


def source_lines(nss):
    rows = []
    for ns in nss:
        for k, v in flat(load('en', ns)).items():
            rows.append((ns, k, v))
    return rows


def export(lang, nss):
    for i, (ns, k, v) in enumerate(source_lines(nss), 1):
        print(f'{i}|{v}')


def apply(lang, path, nss):
    rows = source_lines(nss)
    got = {}
    for line in open(path, encoding='utf8'):
        line = line.rstrip('\n')
        if not line.strip() or '|' not in line:
            continue
        n, text = line.split('|', 1)
        got[int(n)] = text
    by_ns = {}
    problems = []
    for i, (ns, k, v) in enumerate(rows, 1):
        if i not in got:
            continue
        t = got[i]
        if sorted(PH.findall(t)) != sorted(PH.findall(v)):
            problems.append(f'{ns}:{k} placeholders differ')
            continue
        by_ns.setdefault(ns, {})[k] = t
    os.makedirs(os.path.join(ROOT, lang), exist_ok=True)
    for ns, pairs in by_ns.items():
        data = {'_review': 'TODO: machine-drafted, needs review by a native speaker'}
        data.update(unflat(pairs))
        with open(os.path.join(ROOT, lang, f'{ns}.json'), 'w', encoding='utf8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print(f'{lang}: {sum(len(p) for p in by_ns.values())}/{len(rows)} strings written; {len(problems)} rejected')
    for p in problems[:20]:
        print('  ', p)


def loaders():
    langs = sorted(d for d in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, d)) and d not in ('en', 'hi'))
    lines = ['// GENERATED by scripts/i18n-tools.py loaders. Do not edit by hand.',
             '/* eslint-disable @typescript-eslint/no-require-imports -- lazy JSON requires keep unused languages out of memory */',
             "import type { Language } from '@/domain/types';", '',
             'type Bundle = Record<string, object>;', '',
             '/** Translation bundles for languages other than English and Hindi, loaded on first use. */',
             'export const LOADERS: Partial<Record<Language, () => Bundle>> = {']
    for lang in langs:
        files = sorted(f[:-5] for f in os.listdir(os.path.join(ROOT, lang)) if f.endswith('.json'))
        body = ', '.join(f"{ns}: require('./{lang}/{ns}.json')" for ns in files)
        lines.append(f'  {lang}: () => ({{ {body} }}),')
    lines += ['};', '']
    open(os.path.join(ROOT, 'loaders.ts'), 'w', encoding='utf8').write('\n'.join(lines))
    print('loaders.ts:', ', '.join(langs) or '(none)')


def check():
    en = {ns: flat(load('en', ns)) for ns in namespaces()}
    ok = True
    for lang in sorted(os.listdir(ROOT)):
        d = os.path.join(ROOT, lang)
        if lang == 'en' or not os.path.isdir(d):
            continue
        total = done = 0
        for ns, src in en.items():
            tr = flat(load(lang, ns))
            total += len(src)
            for k, v in tr.items():
                if k not in src:
                    print(f'{lang}/{ns}: unknown key {k}'); ok = False
                elif sorted(PH.findall(v)) != sorted(PH.findall(src[k])):
                    print(f'{lang}/{ns}: placeholders differ in {k}'); ok = False
                else:
                    done += 1
        print(f'{lang}: {done}/{total} strings ({round(100 * done / total)}%)')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'export':
        export(sys.argv[2], sys.argv[3:] or CORE)
    elif cmd == 'apply':
        apply(sys.argv[2], sys.argv[3], sys.argv[4:] or CORE)
    elif cmd == 'loaders':
        loaders()
    elif cmd == 'check':
        check()
    else:
        print(__doc__)
